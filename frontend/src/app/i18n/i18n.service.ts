@Injectable({ providedIn: 'root' })
export class I18nService {
  private readonly lang$ = new BehaviorSubject<Lang>(this.load());

  get lang(): Lang {
    return this.lang$.value;
  }

  get langObservable(): Observable<Lang> {
    return this.lang$.asObservable();
  }

  setLang(lang: Lang): void {
    this.lang$.next(lang);
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch {
      /* ignore */
    }
  }

  toggle(): void {
    this.setLang(this.lang === 'fr' ? 'en' : 'fr');
  }

  /** Résout une clé de dictionnaire (notation pointée). Retourne la clé si absente. */
  t(key: string): string {
    const dict = this.lang === 'fr' ? FR : EN;
    return dict[key] ?? FR[key] ?? key;
  }

  /** Traduit une valeur d'énumération métier (statut, priorité, catégorie…). */
  enum(map: string, value: string | null | undefined): string {
    if (value == null || value === '') return '';
    if (this.lang === 'fr') return value; // les valeurs sont stockées en français
    return ENUMS[map]?.[value] ?? value;
  }

  private load(): Lang {
    try {
      const stored = localStorage.getItem(STORAGE_KEY);
      if (stored === 'en' || stored === 'fr') return stored;
    } catch {
      /* ignore */
    }
    // Défaut : navigateur francophone sinon français (l'application est d'abord en français)
    if (typeof navigator !== 'undefined' && /^en\b/i.test(navigator.language)) return 'en';
    return 'fr';
  }
}
